/**
 * Widen the literal string types away while keeping the key structure.
 *
 * Without this, `as const` would type every value as its exact French string
 * and no translation could ever satisfy it. With it, the *shape* is still
 * enforced — a locale missing a key, or inventing one, fails the build.
 */
type Widen<T> = {
  [K in keyof T]: T[K] extends string ? string : Widen<T[K]>;
};

export type Dictionary = Widen<typeof fr>;
